#!/bin/sh
# Merge every prompt log in prompts/ into one chronological list at the end
# of PROMPTS.md (PR B1). The per-person files stay the source of truth: this
# only copies their entries, verbatim, sorted by timestamp. Ties keep file
# order (planning, anirudh, khushi, likith), then in-file order.
#
# An entry starts at a header line "### YYYY-MM-DD HH:MM ..." and runs to
# the next such header. Text before a file's first header (title, format
# example) is not an entry. Rerun after any log changes; it is idempotent.
set -eu
cd "$(dirname "$0")/.."

marker='<!-- Generated by scripts/merge-prompts.sh from prompts/*.md. Do not edit below this line: edit the per-person files and rerun the script. -->'
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

n=0
for f in prompts/planning-claude-ai.md prompts/anirudh.md prompts/khushi.md prompts/likith.md; do
	n=$((n + 1))
	# One file per entry, named <timestamp>-<file index>-<entry index>, so a
	# plain byte sort of the names is the chronological order.
	awk -v src="$f" -v fi="$n" -v dir="$tmp" '
		function flush(   k) {
			if (cnt == 0) return
			while (cnt > 1 && buf[cnt] ~ /^[[:space:]]*$/) cnt--  # drop trailing blank lines
			for (k = 1; k <= cnt; k++) print buf[k] > out
			close(out)
			cnt = 0
		}
		/^### [0-9][0-9][0-9][0-9]-[0-9][0-9]-[0-9][0-9] [0-9][0-9]:[0-9][0-9]/ {
			flush()
			ts = substr($0, 5, 16)
			gsub(/[ :]/, "_", ts)
			out = sprintf("%s/%s-%d-%05d", dir, ts, fi, ++i)
			buf[++cnt] = $0 " | From: " src
			next
		}
		cnt > 0 { buf[++cnt] = $0 }
		END { flush() }
	' "$f"
done

total=$(ls "$tmp" | wc -l | tr -d ' ')
{
	if grep -qF "$marker" PROMPTS.md; then
		sed "/$(printf '%s' "$marker" | sed 's/[][\/.*^$]/\\&/g')/,\$d" PROMPTS.md
	else
		cat PROMPTS.md
		echo
	fi
	echo "$marker"
	echo
	echo "## All prompts in time order"
	echo
	echo "$total prompts. Each header is the original one plus the file it comes from."
	for e in $(ls "$tmp" | LC_ALL=C sort); do
		echo
		cat "$tmp/$e"
	done
} > "$tmp.out"
mv "$tmp.out" PROMPTS.md
echo "PROMPTS.md: $total prompts merged"
